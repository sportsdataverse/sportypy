"""Generate the docs site's pages from sportypy itself.

Usage:
    python tools/gen_docs.py

`yarn start` and `yarn build` in website/ run this first (website/scripts/
gen-docs.mjs), so the site is rebuilt from the docstrings on every build:
locally, in CI and on Vercel. Nothing it writes is committed (website/
.gitignore lists it), so there is no generated file to keep in step by hand.

It writes:
- website/docs/reference/surfaces/<sport>.md: the sport's base class, a table of
  its league classes (with each one's league_code) and its public methods
- website/docs/reference/features/<sport>.md: the features a surface is drawn from
- website/docs/reference/plotting.md: the plotting and display methods every
  surface inherits
- website/docs/reference/index.md: the reference overview
- website/docs/getting-started.md: the README's usage sections
- website/src/pages/CHANGELOG.md: CHANGELOG.md (the canonical changelog)
- website/src/data/home.json and website/static/img/home/<sport>.png: the
  homepage's version, sports, cookbook figures and a drawing of each sport's
  surface
- website/docs/cookbooks/<notebook>.md and website/static/img/cookbooks/: a
  page per notebook in examples/notebooks/, from its saved outputs (notebooks
  are executed by hand, not here: they load live data), and
  website/docs/cookbooks.md, their overview and gallery

The docstrings are NumPy style and are parsed with griffe. A new sport or league
appears once its module or class exists.
"""

from __future__ import annotations

import base64
import importlib
import itertools
import json
import re
import shutil
import sys
from pathlib import Path

import griffe

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "website"
DOCS = SITE / "docs"
REF = DOCS / "reference"
HOME_IMG = SITE / "static" / "img" / "home"
NOTEBOOKS = ROOT / "examples" / "notebooks"
COOKBOOKS = DOCS / "cookbooks"
COOKBOOK_IMG = SITE / "static" / "img" / "cookbooks"
SITE_URL = "https://sportypy.sportsdataverse.org"
REPO_URL = "https://github.com/sportsdataverse/sportypy/"
COLAB_URL = "https://colab.research.google.com/github/sportsdataverse/sportypy/blob/main/"
# how a notebook is (re-)executed in place; see examples/notebooks/README.md
RUN_NOTEBOOK = "uv run --group cookbook jupyter nbconvert --to notebook --execute --inplace"
HEADER = "<!-- Generated by tools/gen_docs.py from {}. Do not edit: it is rebuilt on every build. -->\n"
DOCSTRINGS = HEADER.format("the docstrings")

# The league drawn for each sport on the homepage; a sport not listed here
# uses its first league class
HOME_LEAGUE = {
    "baseball": "MLBField",
    "basketball": "NBACourt",
    "curling": "WCFSheet",
    "football": "NFLField",
    "hockey": "NHLRink",
    "lacrosse": "PLLField",
    "soccer": "FIFAPitch",
    "softball": "NCAASoftballField",
    "tennis": "ITFCourt",
    "volleyball": "FIVBCourt",
}

# draw() arguments for a sport whose whole surface is too long and thin for a
# homepage card (a curling sheet is about 8:1): it shows a part of it instead
HOME_VIEW = {"curling": {"display_range": "house"}}

# Sections of a NumPy docstring rendered as "name (type): description" lists
LISTS = {
    "parameters": "Parameters",
    "other parameters": "Other parameters",
    "attributes": "Attributes",
    "returns": "Returns",
    "yields": "Yields",
    "raises": "Raises",
}
BULLET = re.compile(r"^(\s*)- (.*)$")
TYPED = re.compile(r"^(\w+)\s*:\s*(.+?)\s*$")


def rst_to_md(text: str) -> str:
    """``code`` (reST) to `code` (Markdown)."""
    return re.sub(r"``(.+?)``", r"`\1`", text)


def unwrap(text: str) -> str:
    """Join hard-wrapped lines into paragraphs and bullets. A ``- `` line
    starts a bullet (nested by its indent); a ``- name : type`` bullet is
    shown as `` `name` (type):``."""
    blocks: list[tuple[int | None, list[str]]] = []  # (bullet indent, words)
    current: tuple[int | None, list[str]] | None = None

    for line in text.splitlines():
        stripped = line.strip()
        bullet = BULLET.match(line)
        if not stripped:
            current = None
        elif bullet:
            body = bullet.group(2)
            typed = TYPED.match(body)
            if typed:
                body = f"`{typed.group(1)}` ({typed.group(2)}):"
            current = (len(bullet.group(1)), [body])
            blocks.append(current)
        elif current is None:
            current = (None, [stripped])
            blocks.append(current)
        else:
            current[1].append(stripped)

    indents = sorted({i for i, _ in blocks if i is not None})
    out = []
    for n, (indent, words) in enumerate(blocks):
        if indent is None:
            text_ = " ".join(words)
        else:
            text_ = "  " * indents.index(indent) + "- " + " ".join(words)
        # consecutive bullets form one tight list
        tight = n and indent is not None and blocks[n - 1][0] is not None
        out.append(("\n" if tight else "\n\n") + text_ if n else text_)
    return rst_to_md("".join(out))


def render_docstring(obj: griffe.Object, level: int) -> str:
    """The docstring of ``obj`` as Markdown, sections as level-``level`` headings."""
    if not obj.docstring:
        return ""
    parts = []
    for section in obj.docstring.parse("numpy"):
        kind = section.kind.value
        if kind == "text":
            parts.append(unwrap(section.value))
        elif kind in LISTS:
            rows = []
            for el in section.value:
                name = f"`{el.name}`" if getattr(el, "name", None) else ""
                ann = (
                    f"`{el.annotation}`"
                    if getattr(el, "annotation", None)
                    else ""
                )
                label = " ".join(
                    x for x in (name, f"({ann})" if name and ann else ann) if x
                )
                # every line after the first nests under this item
                desc = (
                    unwrap(el.description or "")
                    .replace("\n", "\n  ")
                    .replace("\n  \n", "\n\n")
                )
                rows.append(f"- {label}: {desc}" if label else f"- {desc}")
            parts.append(f"{'#' * level} {LISTS[kind]}\n\n" + "\n".join(rows))
        elif kind == "examples":
            for sub_kind, value in section.value:
                parts.append(
                    f"```python\n{value}\n```"
                    if sub_kind.value == "examples"
                    else value
                )
        elif isinstance(getattr(section, "value", None), str):
            parts.append(unwrap(section.value))
    return "\n\n".join(p for p in parts if p.strip())


def signature(fn: griffe.Function, owner: str = "") -> str:
    params = []
    for p in fn.parameters:
        if p.name == "self":
            continue
        star = {"variadic positional": "*", "variadic keyword": "**"}.get(
            p.kind.value, ""
        )
        default = (
            f" = {p.default}" if p.default is not None and not star else ""
        )
        params.append(f"{star}{p.name}{default}")
    name = f"{owner}.{fn.name}" if owner else fn.name
    return f"```python\n{name}({', '.join(params)})\n```"


def own(obj: griffe.Object, kind: str) -> list[griffe.Object]:
    """``obj``'s own (non-imported) public members of ``kind`` ("class" or "function")."""
    found = []
    for name, member in obj.members.items():
        if member.is_alias or name.startswith("_"):
            continue
        if (kind == "class" and member.is_class) or (
            kind == "function" and member.is_function
        ):
            found.append(member)
    return found


def first_line(obj: griffe.Object) -> str:
    return (
        rst_to_md(obj.docstring.value.strip().splitlines()[0])
        if obj.docstring
        else ""
    )


def surface_class(sport: str, cls: str):
    return getattr(importlib.import_module(f"sportypy.surfaces.{sport}"), cls)


def league_code(sport: str, cls: str) -> str:
    """The ``league_code`` a league class builds with (read from the live class)."""
    try:
        return getattr(surface_class(sport, cls)(), "league_code", "") or ""
    except Exception:  # noqa: BLE001 — a class that needs arguments just shows no code
        return ""


def split_surface(
    module: griffe.Module,
) -> tuple[griffe.Class, list[griffe.Class]]:
    """The sport's base class (the one no other class in the module derives
    from) and its league classes."""
    classes = own(module, "class")
    names = {c.name for c in classes}
    base = next(
        c for c in classes if not any(str(b) in names for b in c.bases)
    )
    return base, [c for c in classes if c is not base]


def surface_page(sport: str, module: griffe.Module, position: int) -> str:
    base, leagues = split_surface(module)
    title = sport.capitalize()
    lines = [
        f"---\ntitle: {title}\nsidebar_position: {position}\n---\n",
        DOCSTRINGS,
        f"# {title}\n",
        f"`from sportypy.surfaces.{sport} import {base.name}`\n",
        f"## `{base.name}`\n",
        render_docstring(base, 3),
    ]
    if leagues:
        lines += [
            "\n## Leagues\n",
            f"Each class below is a `{base.name}` with that league's rule-book dimensions.\n",
            "| Class | `league_code` | Description |",
            "| --- | --- | --- |",
        ]
        for c in leagues:
            code = league_code(sport, c.name)
            lines.append(
                f"| `{c.name}` | {f'`{code}`' if code else ''} | {first_line(c)} |"
            )
    methods = own(base, "function")
    if methods:
        lines.append("\n## Methods\n")
        for fn in methods:
            lines += [
                f"### `{fn.name}`\n",
                signature(fn, base.name),
                "",
                render_docstring(fn, 4),
                "",
            ]
    return "\n".join(lines)


def feature_page(sport: str, module: griffe.Module, position: int) -> str:
    title = sport.capitalize()
    lines = [
        f"---\ntitle: {title}\nsidebar_position: {position}\n---\n",
        DOCSTRINGS,
        f"# {title} features\n",
        f"The features a {sport} surface is drawn from (`sportypy._feature_classes.{sport}`).\n",
    ]
    for c in own(module, "class"):
        lines += [f"## `{c.name}`\n", render_docstring(c, 3), ""]
    return "\n".join(lines)


def plotting_page(pkg: griffe.Module) -> str:
    lines = [
        "---\ntitle: Plotting and display\nsidebar_position: 2\n---\n",
        DOCSTRINGS,
        "# Plotting and display\n",
        "Every surface inherits these methods: the plotting helpers from `BaseSurfacePlot` "
        "and the display and coordinate methods from `BaseSurface`.\n",
    ]
    for path in (
        "_base_classes._base_surface_plot.BaseSurfacePlot",
        "_base_classes._base_surface.BaseSurface",
    ):
        cls = pkg[path]
        lines.append(f"## `{cls.name}`\n")
        for fn in own(cls, "function"):
            lines += [
                f"### `{fn.name}`\n",
                signature(fn, "surface"),
                "",
                render_docstring(fn, 4),
                "",
            ]
    return "\n".join(lines)


def reference_index(sports: list[dict]) -> str:
    rows = "\n".join(
        f"| [{s['title']}](./surfaces/{s['sport']}.md) | `{s['base']}` | {s['leagues']} |"
        for s in sports
    )
    return (
        "---\ntitle: API reference\nsidebar_label: Overview\nsidebar_position: 0\n---\n\n"
        + DOCSTRINGS
        + "\n# API reference\n\n"
        "Every page here is generated from sportypy's docstrings on each build.\n\n"
        "## Surfaces\n\n"
        "One class per sport, and one subclass per league with that league's rule-book dimensions.\n\n"
        "| Sport | Base class | League classes |\n| --- | --- | --- |\n"
        f"{rows}\n\n"
        "## Shared methods\n\n"
        "[Plotting and display](./plotting.md): the plotting helpers (`scatter`, `heatmap`, `contour`, "
        "`hexbin`, `arrow`, ...) and the display methods every surface has.\n\n"
        "## Features\n\n"
        "The `Features` pages document the shapes each surface is drawn from: useful when adding a "
        "league or a sport.\n"
    )


def changelog_page() -> str:
    body = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    return (
        "---\ntitle: News\n---\n\n"
        + HEADER.format("CHANGELOG.md")
        + "\n"
        + body
    )


def getting_started_page() -> str:
    """The README's usage sections, from "Using the Package" up to the
    community links, so the guide on the site is the README's."""
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    start = readme.index("## Using the Package")
    end = readme.index("## Follow the SportsDataverse")
    return (
        "---\ntitle: Getting started\nsidebar_position: 2\n---\n\n"
        + HEADER.format("README.md")
        + "\n# Getting started\n\n"
        + readme[start:end].rstrip()
        + "\n"
    )


def printed(text: str) -> str:
    """A cell's printed output: the polars tables the notebooks print as
    markdown (pl.Config ASCII_MARKDOWN) become tables, the rest a text block."""
    blocks = []
    for is_table, lines in itertools.groupby(
        text.rstrip("\n").splitlines(), lambda line: line.startswith("|")
    ):
        body = "\n".join(lines)
        blocks.append(body if is_table else f"```text\n{body}\n```")
    return "\n\n".join(blocks)


def notebook_page(path: Path) -> tuple[str, list[dict]]:
    """A cookbook page from an executed notebook, with its figures written
    under COOKBOOK_IMG, and the gallery cards of its cells tagged
    ``gallery``. The notebook must have been run top to bottom in a fresh
    kernel, so the page shows what its code produces."""
    nb = json.loads(path.read_text(encoding="utf-8"))
    meta = nb["metadata"]["sportypy"]
    rel = path.relative_to(ROOT).as_posix()
    counts = [
        c["execution_count"] for c in nb["cells"] if c["cell_type"] == "code"
    ]
    if counts != list(range(1, len(counts) + 1)):
        raise SystemExit(
            f"{rel} has not been run top to bottom in a fresh kernel "
            f"(execution counts {counts}). Run it with:\n  {RUN_NOTEBOOK} {rel}"
        )
    # the notebook's heading is the page title: the comment above it keeps
    # Docusaurus from taking the title from the heading itself
    title = "".join(nb["cells"][0]["source"]).splitlines()[0].lstrip("# ")
    parts = [
        f"---\ntitle: {json.dumps(title)}\n"
        f"sidebar_label: {meta['label']}\n"
        f"sidebar_position: {meta['position']}\n"
        f"description: {json.dumps(meta['description'])}\n"
        f"custom_edit_url: {REPO_URL}blob/main/{rel}\n---",
        HEADER.format(rel).rstrip(),
    ]
    heading, cards = meta["label"], []
    for i, cell in enumerate(nb["cells"]):
        src = "".join(cell["source"])
        if cell["cell_type"] == "markdown":
            # links to the live site stay inside this build, where they are checked
            parts.append(src.replace(SITE_URL, ""))
            for line in src.splitlines():
                if line.startswith("## "):
                    heading = re.sub(r"^\d+\.\s*", "", line[3:])
            if i == 0:
                parts.append(
                    f"[Open in Colab]({COLAB_URL}{rel}) · "
                    f"[View the notebook on GitHub]({REPO_URL}blob/main/{rel})"
                )
            continue
        parts.append(f"```python\n{src}\n```")
        for k, out in enumerate(cell["outputs"]):
            if out["output_type"] == "error":
                raise SystemExit(f"{rel}: cell {i} raised {out['ename']}")
            if out["output_type"] == "stream":
                # stderr is warnings and progress bars, not part of the recipe
                if out["name"] == "stdout":
                    parts.append(printed("".join(out["text"])))
                continue
            data = out.get("data", {})
            if "image/png" in data:
                name = f"{path.stem}-{i}-{k}.png"
                (COOKBOOK_IMG / name).write_bytes(
                    base64.b64decode(data["image/png"])
                )
                alt = f"{meta['label']}: {heading}"
                parts.append(f"![{alt}](/img/cookbooks/{name})")
                if "gallery" in cell["metadata"].get("tags", []):
                    cards.append(
                        {
                            "title": heading,
                            "cookbook": meta["label"],
                            "href": f"/docs/cookbooks/{path.stem}",
                            "img": f"/img/cookbooks/{name}",
                            "alt": alt,
                        }
                    )
            elif "text/markdown" in data:
                parts.append("".join(data["text/markdown"]))
            elif "text/plain" in data:
                parts.append(f"```text\n{''.join(data['text/plain'])}\n```")
    return "\n\n".join(parts), cards


def cookbooks_page(books: list[tuple[Path, dict]], cards: list[dict]) -> str:
    """The cookbooks' overview: a gallery of their tagged figures, then the
    list of cookbooks."""
    gallery = "\n".join(
        f'<a class="cookbook-card" href="{c["href"]}">'
        f'<img src="{c["img"]}" alt="{c["alt"]}" loading="lazy"/>'
        f"<strong>{c['title']}</strong><span>{c['cookbook']}</span></a>"
        for c in cards
    )
    listing = "\n".join(
        f"- [{m['label']}](./cookbooks/{p.stem}.md): {m['description']}"
        for p, m in books
    )
    return (
        "---\ntitle: Cookbooks\nsidebar_label: Overview\n---\n\n"
        + HEADER.format("examples/notebooks/")
        + "\n# Cookbooks\n\n"
        "Worked analyses on real data. sportsdataverse-py loads it, sdvplot "
        "brings team colors and logos, and sportypy draws the surface and bins "
        "the data onto it. Each cookbook is a Jupyter notebook in "
        f"[examples/notebooks]({REPO_URL}tree/main/examples/notebooks), shown "
        "with the output of its last run: open it in Colab or download it to "
        "run it yourself.\n\n"
        f'<div class="cookbook-gallery">\n{gallery}\n</div>\n\n'
        f"## Every cookbook\n\n{listing}\n"
    )


def draw_home_figures(sports: list[dict]) -> None:
    """A drawing of each sport's surface for the homepage (a transparent PNG,
    so it sits on either color mode)."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    from PIL import Image

    def render(sport: str, cls: str, rotation: float) -> Image.Image:
        fig, ax = plt.subplots(figsize=(6, 3.6))
        surface_class(sport, cls)().draw(
            ax=ax, rotation=rotation, **HOME_VIEW.get(sport, {})
        )
        ax.set_axis_off()
        path = HOME_IMG / f"{sport}.png"
        # drawn large, so a surface that fills little of its extent stays sharp
        fig.savefig(path, dpi=220, transparent=True, bbox_inches="tight")
        plt.close(fig)
        # crop to what is drawn: a surface's full extent can be mostly invisible
        # (a baseball field's outfield is transparent by default)
        image = Image.open(path)
        image = image.crop(image.getchannel("A").getbbox())
        if image.width > 640:
            image = image.resize(
                (640, round(image.height * 640 / image.width)), Image.LANCZOS
            )
        image.save(path, optimize=True)
        return image

    HOME_IMG.mkdir(parents=True, exist_ok=True)
    for s in sports:
        image = render(s["sport"], s["example"], 0.0)
        # a tall surface (a curling sheet) is turned sideways to fill its card
        if image.height > image.width:
            render(s["sport"], s["example"], 90.0)


def build() -> dict[Path, str]:
    pkg = griffe.load(
        "sportypy",
        search_paths=[ROOT],
        docstring_parser="numpy",
        allow_inspection=False,
    )
    out: dict[Path, str] = {
        REF / "plotting.md": plotting_page(pkg),
        DOCS / "getting-started.md": getting_started_page(),
        SITE / "src" / "pages" / "CHANGELOG.md": changelog_page(),
    }
    sports = []
    for i, (sport, module) in enumerate(
        sorted(pkg["surfaces"].modules.items()), start=1
    ):
        if not own(module, "class"):
            continue
        base, leagues = split_surface(module)
        names = [c.name for c in leagues]
        sports.append(
            {
                "sport": sport,
                "title": sport.capitalize(),
                "base": base.name,
                "leagues": len(leagues),
                "example": HOME_LEAGUE.get(sport)
                if HOME_LEAGUE.get(sport) in names
                else names[0],
            }
        )
        out[REF / "surfaces" / f"{sport}.md"] = surface_page(sport, module, i)
    for i, (sport, module) in enumerate(
        sorted(pkg["_feature_classes"].modules.items()), start=1
    ):
        if own(module, "class"):
            out[REF / "features" / f"{sport}.md"] = feature_page(
                sport, module, i
            )
    out[REF / "index.md"] = reference_index(sports)

    # a regex, not tomllib: that is Python 3.11+ and sportypy supports 3.10
    version = re.search(
        r'^version = "([^"]+)"',
        (ROOT / "pyproject.toml").read_text(encoding="utf-8"),
        re.M,
    ).group(1)
    home = {
        "version": version,
        "install": "pip install sportypy",
        "sports": sports,
    }
    draw_home_figures(sports)

    COOKBOOK_IMG.mkdir(parents=True, exist_ok=True)
    books, cards = [], []
    for path in sorted(NOTEBOOKS.glob("*.ipynb")):
        page, found = notebook_page(path)
        out[COOKBOOKS / f"{path.stem}.md"] = page
        books.append(
            (
                path,
                json.loads(path.read_text(encoding="utf-8"))["metadata"][
                    "sportypy"
                ],
            )
        )
        cards += found
    books.sort(key=lambda b: b[1]["position"])
    if books:
        out[DOCS / "cookbooks.md"] = cookbooks_page(books, cards)
    home["cookbooks"] = cards
    out[SITE / "src" / "data" / "home.json"] = json.dumps(home, indent=2)
    # no trailing whitespace, one final newline
    return {
        p: "\n".join(line.rstrip() for line in text.splitlines()) + "\n"
        for p, text in out.items()
    }


def main() -> int:
    # rebuild the reference from scratch, so a removed sport or league leaves no page behind
    shutil.rmtree(REF, ignore_errors=True)
    shutil.rmtree(HOME_IMG, ignore_errors=True)
    shutil.rmtree(COOKBOOKS, ignore_errors=True)
    shutil.rmtree(COOKBOOK_IMG, ignore_errors=True)
    pages = build()
    for p, text in pages.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print(
        f"gen_docs: wrote {len(pages)} pages and {len(list(HOME_IMG.glob('*.png')))} surface drawings"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
