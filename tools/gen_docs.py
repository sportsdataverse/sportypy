"""Generate the Docusaurus API reference from sportypy's docstrings.

Usage:
    python tools/gen_docs.py           # write website/docs/reference/ and the changelog
    python tools/gen_docs.py --check   # exit 1 if any generated page is stale

One page per sport for the surfaces (the sport's base class, a table of its
league classes, and its public methods) and for the features, plus a page for
the plotting and display methods every surface inherits. The docstrings are
NumPy style and are parsed with griffe; nothing is hand-maintained here, so a
new sport or league appears once its module exists. docs/changelog.md (the
canonical changelog) is copied to website/docs/changelog.md.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import griffe

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "website" / "docs"
REF = OUT / "reference"
HEADER = "<!-- Generated by tools/gen_docs.py from the docstrings. Do not edit. -->\n"

# Sections of a NumPy docstring rendered as "name (type): description" lists
LISTS = {
    "parameters": "Parameters",
    "other parameters": "Other parameters",
    "attributes": "Attributes",
    "returns": "Returns",
    "yields": "Yields",
    "raises": "Raises",
}
BULLET = re.compile(r"^(\s*)- (.*)$")
TYPED = re.compile(r"^(\w+)\s*:\s*(.+?)\s*$")


def rst_to_md(text: str) -> str:
    """``code`` (reST) to `code` (Markdown)."""
    return re.sub(r"``(.+?)``", r"`\1`", text)


def unwrap(text: str) -> str:
    """Join hard-wrapped lines into paragraphs and bullets. A ``- `` line
    starts a bullet (nested by its indent); a ``- name : type`` bullet is
    shown as `` `name` (type):``."""
    blocks: list[tuple[int | None, list[str]]] = []  # (bullet indent, words)
    current: tuple[int | None, list[str]] | None = None

    for line in text.splitlines():
        stripped = line.strip()
        bullet = BULLET.match(line)
        if not stripped:
            current = None
        elif bullet:
            body = bullet.group(2)
            typed = TYPED.match(body)
            if typed:
                body = f"`{typed.group(1)}` ({typed.group(2)}):"
            current = (len(bullet.group(1)), [body])
            blocks.append(current)
        elif current is None:
            current = (None, [stripped])
            blocks.append(current)
        else:
            current[1].append(stripped)

    indents = sorted({i for i, _ in blocks if i is not None})
    out = []
    for n, (indent, words) in enumerate(blocks):
        if indent is None:
            text_ = " ".join(words)
        else:
            text_ = "  " * indents.index(indent) + "- " + " ".join(words)
        # consecutive bullets form one tight list
        tight = n and indent is not None and blocks[n - 1][0] is not None
        out.append(("\n" if tight else "\n\n") + text_ if n else text_)
    return rst_to_md("".join(out))


def render_docstring(obj: griffe.Object, level: int) -> str:
    """The docstring of ``obj`` as Markdown, sections as level-``level`` headings."""
    if not obj.docstring:
        return ""
    parts = []
    for section in obj.docstring.parse("numpy"):
        kind = section.kind.value
        if kind == "text":
            parts.append(unwrap(section.value))
        elif kind in LISTS:
            rows = []
            for el in section.value:
                name = f"`{el.name}`" if getattr(el, "name", None) else ""
                ann = (
                    f"`{el.annotation}`"
                    if getattr(el, "annotation", None)
                    else ""
                )
                label = " ".join(
                    x for x in (name, f"({ann})" if name and ann else ann) if x
                )
                # every line after the first nests under this item
                desc = (
                    unwrap(el.description or "")
                    .replace("\n", "\n  ")
                    .replace("\n  \n", "\n\n")
                )
                rows.append(f"- {label}: {desc}" if label else f"- {desc}")
            parts.append(f"{'#' * level} {LISTS[kind]}\n\n" + "\n".join(rows))
        elif kind == "examples":
            for sub_kind, value in section.value:
                fence = "```python\n" if sub_kind.value == "examples" else ""
                parts.append(f"{fence}{value}\n```" if fence else value)
        elif hasattr(section, "value") and isinstance(section.value, str):
            parts.append(unwrap(section.value))
    return "\n\n".join(p for p in parts if p.strip())


def signature(fn: griffe.Function, owner: str = "") -> str:
    params = []
    for p in fn.parameters:
        if p.name == "self":
            continue
        star = (
            "*"
            if p.kind.value == "variadic positional"
            else "**"
            if p.kind.value == "variadic keyword"
            else ""
        )
        default = (
            f" = {p.default}" if p.default is not None and not star else ""
        )
        params.append(f"{star}{p.name}{default}")
    name = f"{owner}.{fn.name}" if owner else fn.name
    return f"```python\n{name}({', '.join(params)})\n```"


def own(obj: griffe.Object, kind: str) -> list[griffe.Object]:
    """``obj``'s own (non-imported) public members of ``kind`` ("class" or "function")."""
    found = []
    for name, member in obj.members.items():
        if member.is_alias or name.startswith("_"):
            continue
        if (kind == "class" and member.is_class) or (
            kind == "function" and member.is_function
        ):
            found.append(member)
    return found


def first_line(obj: griffe.Object) -> str:
    return (
        rst_to_md(obj.docstring.value.strip().splitlines()[0])
        if obj.docstring
        else ""
    )


def league_code(module: str, cls: str) -> str:
    """The ``league_code`` a league class builds with (read from the live class)."""
    import importlib

    try:
        return (
            getattr(
                getattr(
                    importlib.import_module(f"sportypy.surfaces.{module}"), cls
                )(),
                "league_code",
                "",
            )
            or ""
        )
    except Exception:  # noqa: BLE001 — a class that needs arguments just shows no code
        return ""


def surface_page(module: griffe.Module, position: int) -> str:
    sport = module.name
    classes = own(module, "class")
    base = next(
        c
        for c in classes
        if not any(str(b) in {c2.name for c2 in classes} for b in c.bases)
    )
    leagues = [c for c in classes if c is not base]
    title = sport.capitalize()
    lines = [
        f"---\ntitle: {title}\nsidebar_position: {position}\n---\n",
        HEADER,
        f"# {title}\n",
        f"`from sportypy.surfaces.{sport} import {base.name}`\n",
        f"## `{base.name}`\n",
        render_docstring(base, 3),
    ]
    if leagues:
        lines += [
            "\n## Leagues\n",
            f"Each class below is a `{base.name}` preset with that league's rule-book dimensions.\n",
            "| Class | `league_code` | Description |",
            "| --- | --- | --- |",
        ]
        for c in leagues:
            code = league_code(sport, c.name)
            lines.append(
                f"| `{c.name}` | {f'`{code}`' if code else ''} | {first_line(c)} |"
            )
    methods = own(base, "function")
    if methods:
        lines.append("\n## Methods\n")
        for fn in methods:
            lines += [
                f"### `{fn.name}`\n",
                signature(fn, base.name),
                "",
                render_docstring(fn, 4),
                "",
            ]
    return "\n".join(lines).rstrip() + "\n"


def feature_page(module: griffe.Module, position: int) -> str:
    title = module.name.capitalize()
    lines = [
        f"---\ntitle: {title}\nsidebar_position: {position}\n---\n",
        HEADER,
        f"# {title} features\n",
        f"The features a {module.name} surface is drawn from (`sportypy._feature_classes.{module.name}`).\n",
    ]
    for c in own(module, "class"):
        lines += [f"## `{c.name}`\n", render_docstring(c, 3), ""]
    return "\n".join(lines).rstrip() + "\n"


def plotting_page(pkg: griffe.Module) -> str:
    lines = [
        "---\ntitle: Plotting and display\nsidebar_position: 1\n---\n",
        HEADER,
        "# Plotting and display\n",
        "Every surface inherits these methods: the plotting helpers from `BaseSurfacePlot` "
        "and the display and coordinate methods from `BaseSurface`.\n",
    ]
    for path in (
        "_base_classes._base_surface_plot.BaseSurfacePlot",
        "_base_classes._base_surface.BaseSurface",
    ):
        cls = pkg[path]
        lines.append(f"## `{cls.name}`\n")
        for fn in own(cls, "function"):
            lines += [
                f"### `{fn.name}`\n",
                signature(fn, "surface"),
                "",
                render_docstring(fn, 4),
                "",
            ]
    return "\n".join(lines).rstrip() + "\n"


def changelog_page() -> str:
    body = (ROOT / "docs" / "changelog.md").read_text(encoding="utf-8")
    return (
        "---\ntitle: Changelog\nsidebar_position: 90\n---\n\n"
        + HEADER
        + "\n"
        + body
    )


def getting_started_page() -> str:
    """The README's usage sections, from "Using the Package" up to the
    community links, so the guide on the site is the README's."""
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    start = readme.index("## Using the Package")
    end = readme.index("## Follow the SportsDataverse")
    return (
        "---\ntitle: Getting started\nsidebar_position: 2\n---\n\n"
        + HEADER.replace("the docstrings", "README.md")
        + "\n# Getting started\n\n"
        + readme[start:end].rstrip()
        + "\n"
    )


def pages() -> dict[Path, str]:
    pkg = griffe.load(
        "sportypy",
        search_paths=[ROOT],
        docstring_parser="numpy",
        allow_inspection=False,
    )
    out = {
        REF / "plotting.md": plotting_page(pkg),
        OUT / "changelog.md": changelog_page(),
        OUT / "getting-started.md": getting_started_page(),
    }
    for i, (name, module) in enumerate(
        sorted(pkg["surfaces"].modules.items()), start=1
    ):
        if own(module, "class"):
            out[REF / "surfaces" / f"{name}.md"] = surface_page(module, i)
    for i, (name, module) in enumerate(
        sorted(pkg["_feature_classes"].modules.items()), start=1
    ):
        if own(module, "class"):
            out[REF / "features" / f"{name}.md"] = feature_page(module, i)
    # no trailing whitespace, so pre-commit's whitespace hook never edits a page
    return {
        p: "\n".join(line.rstrip() for line in text.splitlines()) + "\n"
        for p, text in out.items()
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if a generated page is stale",
    )
    args = parser.parse_args()

    wanted = pages()
    existing = set(REF.rglob("*.md")) | {
        OUT / "changelog.md",
        OUT / "getting-started.md",
    }
    stale = sorted(
        str(p.relative_to(ROOT))
        for p in wanted
        if not p.exists() or p.read_bytes().decode("utf-8") != wanted[p]
    )
    orphans = sorted(
        str(p.relative_to(ROOT)) for p in existing - set(wanted) if p.exists()
    )
    if args.check:
        for p in stale:
            print(f"stale: {p}")
        for p in orphans:
            print(f"orphan: {p}")
        if stale or orphans:
            print("run: uv run python tools/gen_docs.py")
            return 1
        print(f"{len(wanted)} generated pages are current")
        return 0
    for p in orphans:
        (ROOT / p).unlink()
    for p, text in wanted.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print(
        f"wrote {len(wanted)} pages ({len(stale)} changed, {len(orphans)} removed)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
